// ============================================================================
// Code Emitter — generates C# source code strings for Azure Functions wrappers.
//
// Each controller gets its own generated class with one function per action.
// Also generates a shared FunctionResultHelper class with runtime utilities
// for response normalization and query parameter parsing.
// ============================================================================

using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace InvoiceApi.Functions.Generator;

/// <summary>
/// Generates C# source code for Azure Functions HTTP trigger wrapper classes.
/// All methods are static and produce string output for the source generator.
/// </summary>
internal static class CodeEmitter
{
    // ========================================================================
    // Controller Functions File
    // ========================================================================

    /// <summary>
    /// Generates a complete .cs file for a single controller's function wrappers.
    /// The generated class injects the original controller via DI and delegates
    /// each HTTP trigger to the corresponding controller action.
    /// </summary>
    public static string EmitControllerFunctions(ControllerInfo controller)
    {
        var sb = new StringBuilder();

        // File header
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("// This file was auto-generated by InvoiceApi.Functions.Generator.");
        sb.AppendLine("// Do not modify this file manually — changes will be overwritten on build.");
        sb.AppendLine("// Source controller: " + controller.FullyQualifiedName);
        sb.AppendLine();
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        // Using directives — core namespaces needed by all generated functions
        sb.AppendLine("using System;");
        sb.AppendLine("using System.Threading;");
        sb.AppendLine("using System.Threading.Tasks;");
        sb.AppendLine("using Microsoft.AspNetCore.Http;");
        sb.AppendLine("using Microsoft.AspNetCore.Mvc;");
        sb.AppendLine("using Microsoft.Azure.Functions.Worker;");

        // Add controller's own namespace
        sb.AppendLine("using " + controller.Namespace + ";");

        // Add extra namespaces collected from parameter types
        foreach (var ns in controller.RequiredNamespaces
            .Where(n => !string.IsNullOrEmpty(n) &&
                        n != controller.Namespace &&
                        n != "System" &&
                        n != "System.Threading" &&
                        n != "System.Threading.Tasks")
            .OrderBy(n => n))
        {
            sb.AppendLine("using " + ns + ";");
        }

        sb.AppendLine();
        sb.AppendLine("namespace InvoiceApi.Functions.Generated;");
        sb.AppendLine();

        // Class XML doc
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Auto-generated Azure Functions HTTP triggers wrapping " + controller.ClassName + ".");
        sb.AppendLine("/// Each public [Http*] action method is exposed as a separate Azure Function.");
        sb.AppendLine("/// The controller is injected via DI and receives the current HttpContext");
        sb.AppendLine("/// so it has access to User claims, request data, etc.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public class " + controller.FunctionClassName);
        sb.AppendLine("{");

        // Constructor — inject the controller via DI
        sb.AppendLine("    private readonly " + controller.ClassName + " _controller;");
        sb.AppendLine();
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// Constructor — the controller is resolved from the DI container.");
        sb.AppendLine("    /// AddControllersAsServices() in Program.cs enables this injection pattern.");
        sb.AppendLine("    /// </summary>");
        sb.AppendLine("    public " + controller.FunctionClassName + "(" +
                      controller.ClassName + " controller)");
        sb.AppendLine("    {");
        sb.AppendLine("        _controller = controller;");
        sb.AppendLine("    }");

        // Generate a function method for each action
        foreach (var action in controller.Actions)
        {
            sb.AppendLine();
            EmitFunctionMethod(sb, action, controller);
        }

        sb.AppendLine("}");

        return sb.ToString();
    }

    /// <summary>
    /// Generates a single [Function] + [HttpTrigger] method that wraps a controller action.
    /// Handles: auth checks, parameter extraction, controller context setup, and result normalization.
    /// </summary>
    private static void EmitFunctionMethod(
        StringBuilder sb,
        ActionInfo action,
        ControllerInfo controller)
    {
        // Determine if the generated function needs to be async
        bool needsAsync = action.IsAsync || action.HasBodyParam;

        // Build the function signature
        string returnType = needsAsync ? "async Task<IActionResult>" : "IActionResult";

        // XML doc for the function
        sb.AppendLine("    /// <summary>");
        sb.AppendLine("    /// " + action.HttpMethod.ToUpper() + " " + action.Route +
                      " → " + controller.ClassName + "." + action.MethodName);
        sb.AppendLine("    /// </summary>");

        // [Function] attribute with unique function name
        sb.AppendLine("    [Function(\"" + action.FunctionName + "\")]");

        // Method signature with [HttpTrigger] on the HttpRequest parameter
        sb.Append("    public " + returnType + " " + action.FunctionName + "(");
        sb.AppendLine();

        // HttpTrigger attribute — specifies HTTP method and route
        sb.Append("        [HttpTrigger(AuthorizationLevel.Anonymous, \"" +
                  action.HttpMethod + "\", Route = \"" + action.Route + "\")] HttpRequest req");

        // Add route parameters as function parameters (Azure Functions binds them automatically)
        foreach (var param in action.Parameters.Where(p => p.Source == BindingSource.Route))
        {
            sb.AppendLine(",");
            sb.Append("        " + param.FullTypeName + " " + param.Name);
        }

        sb.AppendLine(")");
        sb.AppendLine("    {");

        // Step 1: Set up ControllerContext so the controller has access to HttpContext, User, etc.
        sb.AppendLine("        // Wire up the controller's HttpContext so it can access User claims, Request, etc.");
        sb.AppendLine("        _controller.ControllerContext = new ControllerContext { HttpContext = req.HttpContext };");
        sb.AppendLine();

        // Step 2: Authorization check (if required)
        EmitAuthCheck(sb, action.Auth);

        // Step 3: Extract parameters from query string and body
        EmitParameterExtraction(sb, action);

        // Step 4: Call the controller method and normalize the result
        EmitMethodCall(sb, action, needsAsync);

        sb.AppendLine("    }");
    }

    // ========================================================================
    // Auth Check Generation
    // ========================================================================

    /// <summary>
    /// Generates authorization check code based on the action's auth requirements.
    /// [AllowAnonymous] → no check. [Authorize] → check IsAuthenticated.
    /// [Authorize(Roles = "...")] → check IsAuthenticated + IsInRole.
    /// </summary>
    private static void EmitAuthCheck(StringBuilder sb, AuthInfo auth)
    {
        // No auth or [AllowAnonymous] — skip check
        if (auth == null || auth.AllowAnonymous)
        {
            sb.AppendLine("        // No authentication required ([AllowAnonymous] or no [Authorize])");
            sb.AppendLine();
            return;
        }

        if (auth.RequireAuth)
        {
            // Check if user is authenticated
            sb.AppendLine("        // Authorization check: [Authorize" +
                          (auth.Roles != null ? "(Roles = \"" + auth.Roles + "\")" : "") + "]");
            sb.AppendLine("        if (req.HttpContext.User.Identity?.IsAuthenticated != true)");
            sb.AppendLine("            return new UnauthorizedResult();");

            // Check roles if specified
            if (auth.Roles != null)
            {
                sb.AppendLine();
                sb.AppendLine("        // Role check: user must be in one of [" + auth.Roles + "]");

                var roles = auth.Roles.Split(',');
                if (roles.Length == 1)
                {
                    sb.AppendLine("        if (!req.HttpContext.User.IsInRole(\"" +
                                  roles[0].Trim() + "\"))");
                    sb.AppendLine("            return new ForbidResult();");
                }
                else
                {
                    // Multiple roles — user needs at least one
                    sb.Append("        if (");
                    for (int i = 0; i < roles.Length; i++)
                    {
                        if (i > 0) sb.Append(" && ");
                        sb.Append("!req.HttpContext.User.IsInRole(\"" + roles[i].Trim() + "\")");
                    }
                    sb.AppendLine(")");
                    sb.AppendLine("            return new ForbidResult();");
                }
            }

            sb.AppendLine();
        }
    }

    // ========================================================================
    // Parameter Extraction Generation
    // ========================================================================

    /// <summary>
    /// Generates code to extract parameters from the HTTP request.
    /// Route params are already bound by Azure Functions runtime.
    /// Query params are parsed from req.Query. Body params are deserialized from JSON.
    /// </summary>
    private static void EmitParameterExtraction(StringBuilder sb, ActionInfo action)
    {
        bool hasExtractions = false;

        foreach (var param in action.Parameters)
        {
            switch (param.Source)
            {
                case BindingSource.Route:
                    // Route params are bound by Azure Functions runtime as function parameters.
                    // No extraction needed — they're passed directly to the function method.
                    break;

                case BindingSource.Body:
                    // Deserialize JSON body to the parameter type
                    hasExtractions = true;
                    sb.AppendLine("        // Deserialize request body → " + param.ShortTypeName);
                    sb.AppendLine("        var " + param.Name +
                                  " = await System.Text.Json.JsonSerializer.DeserializeAsync<" +
                                  param.FullTypeName + ">(req.Body, FunctionResultHelper.JsonOptions, " +
                                  "req.HttpContext.RequestAborted);");
                    break;

                case BindingSource.CancellationToken:
                    // Use the request's cancellation token
                    hasExtractions = true;
                    sb.AppendLine("        var " + param.Name + " = req.HttpContext.RequestAborted;");
                    break;

                case BindingSource.Query:
                    hasExtractions = true;
                    EmitQueryParameterExtraction(sb, param);
                    break;
            }
        }

        if (hasExtractions)
            sb.AppendLine();
    }

    /// <summary>
    /// Generates code to extract a single query parameter from req.Query.
    /// Handles: strings, integers, booleans, enums (nullable and non-nullable),
    /// DateTime, and complex DTO types (via FunctionResultHelper.BindFromQuery).
    /// </summary>
    private static void EmitQueryParameterExtraction(StringBuilder sb, ParamInfo param)
    {
        // Complex DTO type → use reflection-based query binder
        if (!param.IsSimpleType)
        {
            sb.AppendLine("        // Bind complex DTO from query string parameters");
            sb.AppendLine("        var " + param.Name +
                          " = FunctionResultHelper.BindFromQuery<" +
                          param.FullTypeName + ">(req.Query);");
            return;
        }

        // Simple types — extract from req.Query and parse
        var queryKey = ToCamelCase(param.Name);

        if (param.IsEnum)
        {
            // Enum or nullable enum — use Enum.TryParse
            if (param.IsNullable)
            {
                sb.AppendLine("        // Parse nullable enum from query: ?" + queryKey + "=Value");
                sb.AppendLine("        " + param.FullTypeName + " " + param.Name +
                              " = req.Query.TryGetValue(\"" + queryKey + "\", out var _" + param.Name + "Val) && " +
                              "Enum.TryParse(_" + param.Name + "Val.ToString(), true, out " +
                              GetUnderlyingEnumType(param.FullTypeName) + " _" + param.Name + "Parsed)");
                sb.AppendLine("            ? _" + param.Name + "Parsed");
                sb.AppendLine("            : null;");
            }
            else
            {
                sb.AppendLine("        // Parse enum from query: ?" + queryKey + "=Value");
                sb.AppendLine("        Enum.TryParse(req.Query[\"" + queryKey + "\"].ToString(), true, out " +
                              param.FullTypeName + " " + param.Name + ");");
            }
        }
        else
        {
            // Non-enum simple type
            var specialType = GetSpecialTypeName(param.FullTypeName);

            switch (specialType)
            {
                case "string":
                    if (param.IsNullable)
                    {
                        sb.AppendLine("        string? " + param.Name +
                                      " = req.Query.TryGetValue(\"" + queryKey + "\", out var _" + param.Name + "Val)" +
                                      " ? _" + param.Name + "Val.ToString() : null;");
                    }
                    else
                    {
                        var defaultStr = param.HasDefaultValue && param.DefaultValue != null
                            ? "\"" + param.DefaultValue + "\""
                            : "\"\"";
                        sb.AppendLine("        string " + param.Name + " = req.Query[\"" + queryKey +
                                      "\"].ToString() ?? " + defaultStr + ";");
                    }
                    break;

                case "bool":
                    EmitValueTypeParse(sb, param, queryKey, "bool", "bool.TryParse", "false");
                    break;

                case "int":
                    EmitValueTypeParse(sb, param, queryKey, "int", "int.TryParse", "0");
                    break;

                case "long":
                    EmitValueTypeParse(sb, param, queryKey, "long", "long.TryParse", "0");
                    break;

                case "double":
                    EmitValueTypeParse(sb, param, queryKey, "double", "double.TryParse", "0");
                    break;

                case "decimal":
                    EmitValueTypeParse(sb, param, queryKey, "decimal", "decimal.TryParse", "0");
                    break;

                case "DateTime":
                    EmitValueTypeParse(sb, param, queryKey, "DateTime", "DateTime.TryParse", null);
                    break;

                case "Guid":
                    EmitValueTypeParse(sb, param, queryKey, "Guid", "Guid.TryParse", null);
                    break;

                default:
                    // Unknown simple type — try generic parse
                    sb.AppendLine("        // Unknown type: " + param.FullTypeName + " — using string value");
                    sb.AppendLine("        var " + param.Name + " = req.Query[\"" + queryKey + "\"].ToString();");
                    break;
            }
        }
    }

    /// <summary>
    /// Generates TryParse code for a value type query parameter.
    /// Handles both nullable and non-nullable variants with default values.
    /// </summary>
    private static void EmitValueTypeParse(
        StringBuilder sb, ParamInfo param, string queryKey,
        string typeName, string tryParseMethod, string fallbackDefault)
    {
        if (param.IsNullable)
        {
            sb.AppendLine("        " + typeName + "? " + param.Name +
                          " = " + tryParseMethod + "(req.Query[\"" + queryKey + "\"], out var _" +
                          param.Name + "Parsed) ? _" + param.Name + "Parsed : null;");
        }
        else
        {
            var defaultValue = param.HasDefaultValue && param.DefaultValue != null
                ? param.DefaultValue
                : fallbackDefault ?? "default";
            sb.AppendLine("        " + tryParseMethod + "(req.Query[\"" + queryKey + "\"], out var " +
                          param.Name + ");");
            // If it has a non-zero default and TryParse fails (returns false + default(T)), set the default
            if (param.HasDefaultValue && param.DefaultValue != null && param.DefaultValue != "0" && param.DefaultValue != "false")
            {
                sb.AppendLine("        if (!req.Query.ContainsKey(\"" + queryKey + "\")) " +
                              param.Name + " = " + param.DefaultValue + ";");
            }
        }
    }

    // ========================================================================
    // Method Call Generation
    // ========================================================================

    /// <summary>
    /// Generates the controller method call and result normalization.
    /// Uses FunctionResultHelper.Normalize to convert CreatedAtActionResult → ObjectResult(201).
    /// </summary>
    private static void EmitMethodCall(StringBuilder sb, ActionInfo action, bool needsAsync)
    {
        sb.AppendLine("        // Call the controller action and normalize the response");

        // Build the argument list in the order the controller method expects
        var args = new List<string>();
        foreach (var param in action.Parameters)
        {
            if (param.Source == BindingSource.Body)
            {
                // Body param: pass the deserialized variable (non-null assertion for value types)
                args.Add(param.Name + (param.IsNullable ? "" : "!"));
            }
            else
            {
                // Route, Query, CancellationToken: pass by name
                args.Add(param.Name);
            }
        }

        var argList = string.Join(", ", args);
        var awaitPrefix = (needsAsync && action.IsAsync) ? "await " : "";

        sb.AppendLine("        return FunctionResultHelper.Normalize(" +
                      awaitPrefix + "_controller." + action.MethodName + "(" + argList + "));");
    }

    // ========================================================================
    // Helper Class Generation (emitted once via RegisterPostInitializationOutput)
    // ========================================================================

    /// <summary>
    /// Generates the FunctionResultHelper class with runtime utilities:
    /// - Normalize: converts CreatedAtActionResult → ObjectResult(201)
    /// - BindFromQuery: reflection-based complex DTO binding from query string
    /// - JsonOptions: shared System.Text.Json serializer options
    /// </summary>
    public static string EmitHelperClass()
    {
        return @"// <auto-generated/>
// Runtime helper class for Azure Functions HTTP trigger wrappers.
// Provides response normalization and query parameter binding utilities.

#nullable enable

using System;
using System.ComponentModel;
using System.Reflection;
using System.Text.Json;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Mvc;

namespace InvoiceApi.Functions.Generated;

/// <summary>
/// Runtime utilities shared by all generated function wrapper classes.
/// Handles response normalization (CreatedAtAction → ObjectResult) and
/// query parameter binding for complex DTO types.
/// </summary>
internal static class FunctionResultHelper
{
    /// <summary>
    /// Shared JSON serializer options matching the default ASP.NET Core configuration.
    /// Uses camelCase property naming to match standard API responses.
    /// </summary>
    public static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNameCaseInsensitive = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase
    };

    // ====================================================================
    // Response Normalization
    // ====================================================================

    /// <summary>
    /// Normalizes an IActionResult for Azure Functions compatibility.
    /// Converts MVC-specific results (CreatedAtAction, CreatedAtRoute) that require
    /// the MVC routing infrastructure into simple ObjectResult with 201 status code.
    /// Other result types pass through unchanged.
    /// </summary>
    public static IActionResult Normalize(IActionResult result)
    {
        // CreatedAtActionResult requires MVC URL routing which isn't available in Functions.
        // Convert to a plain 201 ObjectResult with the same body — the Location header is lost
        // but SPA frontends (Blazor WASM) don't typically use it.
        if (result is CreatedAtActionResult created)
            return new ObjectResult(created.Value) { StatusCode = StatusCodes.Status201Created };

        if (result is CreatedAtRouteResult createdAtRoute)
            return new ObjectResult(createdAtRoute.Value) { StatusCode = StatusCodes.Status201Created };

        return result;
    }

    /// <summary>
    /// Normalizes an ActionResult&lt;T&gt; for Azure Functions compatibility.
    /// Unwraps the ActionResult envelope: if Result is set (explicit IActionResult like NotFound),
    /// normalizes it; if Value is set (implicit return of T), wraps in OkObjectResult.
    /// </summary>
    public static IActionResult Normalize<T>(ActionResult<T> result)
    {
        // Explicit IActionResult (NotFound, BadRequest, CreatedAtAction, etc.)
        if (result.Result != null)
            return Normalize(result.Result);

        // Implicit value return (controller returned T directly → wrap in 200 OK)
        return new OkObjectResult(result.Value);
    }

    // ====================================================================
    // Query Parameter Binding for Complex DTOs
    // ====================================================================

    /// <summary>
    /// Binds a complex DTO from query string parameters using reflection.
    /// For each public settable property on T, reads the matching query string key
    /// (camelCase) and converts the string value to the property's type.
    ///
    /// This replaces ASP.NET Core's built-in model binding for [FromQuery] DTOs
    /// (e.g., InvoiceFilterDto, ClientFilterDto) which isn't available in Functions.
    ///
    /// Example: ?page=1&amp;pageSize=10&amp;search=test → new FilterDto { Page=1, PageSize=10, Search=""test"" }
    /// </summary>
    public static T BindFromQuery<T>(IQueryCollection query) where T : new()
    {
        var obj = new T();
        var properties = typeof(T).GetProperties(BindingFlags.Public | BindingFlags.Instance);

        foreach (var prop in properties)
        {
            if (!prop.CanWrite) continue;

            // Try both camelCase and PascalCase key names
            var camelKey = char.ToLowerInvariant(prop.Name[0]) + prop.Name.Substring(1);
            string? rawValue = null;

            if (query.TryGetValue(camelKey, out var camelVal))
                rawValue = camelVal.ToString();
            else if (query.TryGetValue(prop.Name, out var pascalVal))
                rawValue = pascalVal.ToString();

            if (rawValue == null) continue;

            try
            {
                var targetType = Nullable.GetUnderlyingType(prop.PropertyType) ?? prop.PropertyType;

                object? converted;
                if (targetType.IsEnum)
                {
                    converted = Enum.Parse(targetType, rawValue, ignoreCase: true);
                }
                else
                {
                    var converter = TypeDescriptor.GetConverter(targetType);
                    converted = converter.ConvertFromInvariantString(rawValue);
                }

                prop.SetValue(obj, converted);
            }
            catch
            {
                // Skip properties that fail to parse — same behavior as ASP.NET Core model binding
            }
        }

        return obj;
    }
}";
    }

    // ========================================================================
    // String Utilities
    // ========================================================================

    /// <summary>
    /// Converts a PascalCase or camelCase name to camelCase (for query string keys).
    /// ASP.NET Core uses camelCase for query parameter binding by convention.
    /// </summary>
    private static string ToCamelCase(string name)
    {
        if (string.IsNullOrEmpty(name)) return name;
        if (char.IsLower(name[0])) return name;
        return char.ToLowerInvariant(name[0]) + name.Substring(1);
    }

    /// <summary>
    /// Maps a fully qualified type name to a short C# keyword/name for switch-case matching.
    /// E.g., "global::System.Int64" → "long", "global::System.String" → "string"
    /// </summary>
    private static string GetSpecialTypeName(string fullTypeName)
    {
        // Remove global:: prefix and nullable ? suffix
        var name = fullTypeName;
        if (name.StartsWith("global::"))
            name = name.Substring("global::".Length);
        if (name.EndsWith("?"))
            name = name.Substring(0, name.Length - 1);

        // Unwrap System.Nullable<T>
        if (name.StartsWith("System.Nullable<") && name.EndsWith(">"))
        {
            name = name.Substring("System.Nullable<".Length, name.Length - "System.Nullable<".Length - 1);
            if (name.StartsWith("global::"))
                name = name.Substring("global::".Length);
        }

        switch (name)
        {
            case "System.String": case "string": return "string";
            case "System.Boolean": case "bool": return "bool";
            case "System.Int32": case "int": return "int";
            case "System.Int64": case "long": return "long";
            case "System.Double": case "double": return "double";
            case "System.Decimal": case "decimal": return "decimal";
            case "System.Single": case "float": return "float";
            case "System.DateTime": return "DateTime";
            case "System.DateTimeOffset": return "DateTimeOffset";
            case "System.Guid": return "Guid";
            default: return name;
        }
    }

    /// <summary>
    /// Extracts the underlying enum type from a Nullable&lt;TEnum&gt; fully qualified name.
    /// E.g., "global::InvoiceApi.Domain.Enum.EDocumentType?" → "global::InvoiceApi.Domain.Enum.EDocumentType"
    /// </summary>
    private static string GetUnderlyingEnumType(string fullTypeName)
    {
        // Remove nullable ? suffix
        if (fullTypeName.EndsWith("?"))
            return fullTypeName.Substring(0, fullTypeName.Length - 1);

        // Handle Nullable<T> generic
        if (fullTypeName.Contains("Nullable<"))
        {
            var start = fullTypeName.IndexOf("Nullable<") + "Nullable<".Length;
            var end = fullTypeName.LastIndexOf(">");
            if (end > start)
                return fullTypeName.Substring(start, end - start);
        }

        return fullTypeName;
    }
}
